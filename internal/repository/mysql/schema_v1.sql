CREATE TABLE IF NOT EXISTS classes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(255) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 username VARCHAR(255) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(7) NOT NULL CHECK (role IN ('teacher','student')),
 class_id BIGINT NOT NULL,
 session_version BIGINT NOT NULL DEFAULT 0,
 FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS sessions (
 sid_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 data LONGTEXT NOT NULL,
 expires_at BIGINT NOT NULL,
 INDEX sessions_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS materials (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 class_id BIGINT NOT NULL,
 uploader_id BIGINT NOT NULL,
 original_name LONGTEXT NOT NULL,
 size BIGINT NOT NULL CHECK (size>0),
 content_type TEXT NOT NULL,
 storage_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 created_at VARCHAR(32) NOT NULL,
 UNIQUE (id,class_id),
 INDEX materials_class_created(class_id,created_at,id),
 FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE RESTRICT,
 FOREIGN KEY (uploader_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS knowledge_entries (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 material_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 class_id BIGINT NOT NULL,
 plain_text LONGTEXT NOT NULL,
 created_at VARCHAR(32) NOT NULL,
 FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE RESTRICT,
 FOREIGN KEY (material_id,class_id) REFERENCES materials(id,class_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS assignments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS assistants (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE IF NOT EXISTS skills (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
